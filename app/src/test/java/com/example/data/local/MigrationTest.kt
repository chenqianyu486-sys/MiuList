            """.trimIndent()
        )
        db.execSQL(
            """
            INSERT INTO `course_slots` (`id`,`courseId`,`dayOfWeek`,`startPeriod`,`endPeriod`,`classroom`)
            VALUES (1,1,1,1,2,'教二-301'), (2,1,3,3,4,'教二-105')
            """.trimIndent()
        )
        db.execSQL(
            """
            INSERT INTO `tasks`
              (`id`,`courseId`,`courseName`,`courseCategory`,`courseColorHex`,`title`,`description`,
               `taskType`,`startTimeTimestamp`,`startTimeString`,`dueDateTimestamp`,`dueDateString`,
               `priority`,`isCompleted`,`completedAt`,`isAutoGenerated`,`generatedDate`,`createdAt`)
            VALUES (1,1,'高等数学','公共基础','#93C5FD','第 5 周作业','',  'POST_CLASS',
                    0,'周三 10:00 (第3-4节)',1790000000000,'2026-10-12 23:59','MEDIUM',0,NULL,1,'2026-10-05',1790000000000)
            """.trimIndent()
        )

        db.execSQL("PRAGMA user_version = 3")
        db.close()
    }

    private fun openWithMigrations(): AppDatabase =
        Room.databaseBuilder(context, AppDatabase::class.java, dbName)
            .addMigrations(
                MIGRATION_3_4, MIGRATION_4_5, MIGRATION_5_6, MIGRATION_6_7, MIGRATION_7_8,
                MIGRATION_8_9, MIGRATION_9_10, MIGRATION_10_11, MIGRATION_11_12
            )
            .build()

    /**
     * 造一个**真的处在 v5** 的库，用来单独验 v5 → v6。
     *
     * 和 [createVersion4Database] 同一个套路：先跑 MIGRATION_3_4 停在 4，
     * 再用一个声明版本 5 的 OpenHelper 跑 MIGRATION_4_5。
     * 顺手塞进「复习总结 / 其他」两种已经不存在于代码里的历史类型，
     * 这样迁移把它们改写成空串这件事才有东西可断言。
     */
    private fun createVersion5Database() {
        createVersion4Database()

        val helper = FrameworkSQLiteOpenHelperFactory().create(
            SupportSQLiteOpenHelper.Configuration.builder(context)
                .name(dbName)
                .callback(object : SupportSQLiteOpenHelper.Callback(5) {
                    override fun onCreate(db: SupportSQLiteDatabase) = Unit
                    override fun onUpgrade(db: SupportSQLiteDatabase, oldVersion: Int, newVersion: Int) {
                        MIGRATION_4_5.migrate(db)
                    }
                })
                .build()
        )
        try {
            helper.writableDatabase.execSQL(
                """
                INSERT INTO `tasks`
                  (`id`,`courseId`,`courseName`,`courseCategory`,`courseColorHex`,`title`,`description`,
                   `taskType`,`startTimeTimestamp`,`startTimeString`,`dueDateTimestamp`,`dueDateString`,
                   `priority`,`isCompleted`,`completedAt`,`isAutoGenerated`,`generatedDate`,
                   `week`,`dayOfWeek`,`createdAt`)
                VALUES (2,1,'高等数学','公共基础','#93C5FD','第 5 周复习','','REVIEW',
                        0,'',1790000000000,'2026-10-12 23:59','LOW',0,NULL,1,'2026-10-05',5,3,1790000000000),
                       (3,1,'高等数学','公共基础','#93C5FD','第 5 周其他','','CUSTOM',
                        0,'',1790000000000,'2026-10-12 23:59','LOW',0,NULL,1,'2026-10-05',5,3,1790000000000)
                """.trimIndent()
            )
            // 历史遗留的脏规则：这两种类型在 v5 的代码里永远不会被开启，
            // 真有残留只可能是导入进来的，迁移该顺手清掉。
            helper.writableDatabase.execSQL(
                """
                INSERT INTO `task_generation_rules`
                  (`courseId`,`taskType`,`cadence`,`dueOffsetDays`,`dueBeforeMinutes`)
                VALUES (1,'REVIEW','PER_WEEK',6,5), (1,'POST_CLASS','PER_WEEK',6,5)
                """.trimIndent()
            )
        } finally {
            helper.close()
        }
    }

    /**
     * 造一个**真的处在 v4** 的库。
     *
     * 不能靠「只用 MIGRATION_3_4 打开」来停在 v4：Room 要求能从库里的版本一路走到
     * 当前版本（5），少注册一段就直接抛 "A migration from 3 to 5 was required but not found"。
     * 所以这里手动把 MIGRATION_3_4 跑在裸库上，把 user_version 定在 4，再交给 Room 打开 ——
     * 这样 v4→v5 是被真正单独执行的那一步，而不是搭车跑完两段。
     */
    private fun createVersion4Database() {
        createVersion3Database()

        // 用公开的 OpenHelper 把这个 v3 库升到 v4：声明版本 4、onUpgrade 里跑
        // MIGRATION_3_4，helper 收尾时会把 user_version 写成 4。
        // （不能直接调 MIGRATION_3_4.migrate(rawDb)：Migration 要的是 SupportSQLiteDatabase，
        //   而 FrameworkSQLiteDatabase 在 androidx 里是 internal 的。）
        val helper = FrameworkSQLiteOpenHelperFactory().create(
            SupportSQLiteOpenHelper.Configuration.builder(context)
                .name(dbName)
                .callback(object : SupportSQLiteOpenHelper.Callback(4) {
                    override fun onCreate(db: SupportSQLiteDatabase) = Unit
                    override fun onUpgrade(db: SupportSQLiteDatabase, oldVersion: Int, newVersion: Int) {
                        MIGRATION_3_4.migrate(db)
                    }
                })
                .build()
        )
        try {
            // v4 的类别规则还没有 preDueBeforeMinutes 一列 —— 正是 v5 要补默认值的那张表
            helper.writableDatabase.execSQL(
                """
                INSERT INTO `category_rules`
                  (`category`,`preStudy`,`postHomework`,`labReport`,`defaultPostDays`,`defaultMinutes`)
                VALUES ('公共基础',1,1,0,3,30)
                """.trimIndent()
            )
        } finally {
            helper.close()
        }
    }

    @Test
    fun `upgrading from v3 keeps every existing row and seeds the timetable`() = runBlocking {
        createVersion3Database()
        val db = openWithMigrations()
        try {
            // 打开成功本身就是第一层断言：Room 会在迁移后校验 schema，
            // 对不上会在这里抛 IllegalStateException，而不是静默放行。
            val courses = db.courseDao().getAllCoursesOnce()
            assertEquals(1, courses.size)
            val course = courses.first()
            assertEquals("高等数学", course.name)
            assertEquals("MATH101", course.code)
            assertEquals("#93C5FD", course.colorHex)
            // 三个开关已经不是当年那组了：这门课是「公共基础 / (预习开,作业开,实验关)」，
            // 与 v7 的内置默认值逐位相同，于是 v7 → v8 按旧种子判据把它改成「只作业」。
            // 行本身一条不少地活下来（上面 3 行断言的就是这件事），变的是默认取值的版本。
            assertFalse(course.autoPreStudy)
            assertTrue(course.autoPostHomework)
            assertFalse(course.autoLabReport)

            assertEquals("两个时段一条都不能少", 2, db.courseSlotDao().getAllSlotsOnce().size)
            assertEquals(1, db.taskDao().getAllTasksOnce().size)
        } finally {
            db.close()
        }
    }

