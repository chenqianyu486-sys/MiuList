    private fun createVersion3Database() {
        val file = context.getDatabasePath(dbName)
        file.parentFile?.mkdirs()
        if (file.exists()) file.delete()

        val db = SQLiteDatabase.openOrCreateDatabase(file, null)
        db.execSQL(V3_COURSES)
        db.execSQL(V3_COURSE_SLOTS)
        db.execSQL("CREATE INDEX IF NOT EXISTS `index_course_slots_courseId` ON `course_slots` (`courseId`)")
        db.execSQL(
            "CREATE INDEX IF NOT EXISTS `index_course_slots_dayOfWeek_startPeriod` " +
                "ON `course_slots` (`dayOfWeek`, `startPeriod`)"
        )
        db.execSQL(V3_TASKS)
        db.execSQL("CREATE INDEX IF NOT EXISTS `index_tasks_courseId` ON `tasks` (`courseId`)")
        db.execSQL("CREATE INDEX IF NOT EXISTS `index_tasks_dueDateTimestamp` ON `tasks` (`dueDateTimestamp`)")
        db.execSQL("CREATE INDEX IF NOT EXISTS `index_tasks_startTimeTimestamp` ON `tasks` (`startTimeTimestamp`)")
        db.execSQL("CREATE INDEX IF NOT EXISTS `index_tasks_isCompleted` ON `tasks` (`isCompleted`)")

        // 一份典型的老数据：一门两次排课的课 + 一条它的待办
        db.execSQL(
            """
            INSERT INTO `courses`
              (`id`,`name`,`code`,`category`,`teacher`,`classroom`,`colorHex`,
               `autoPreStudy`,`autoPostHomework`,`autoLabReport`,`autoReview`,
               `defaultPostDueDays`,`preStudyEstimatedMinutes`,`postHomeworkEstimatedMinutes`,
               `labReportEstimatedMinutes`)
