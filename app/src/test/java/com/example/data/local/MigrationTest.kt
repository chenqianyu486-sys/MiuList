    @Test
    fun `a v3 database with duplicate courses still migrates`() = runBlocking {
        createVersion3Database()
        // dedupeKey 用非唯一索引的原因就在这里：历史数据可能已经有重复课程，
        // 唯一索引会让这个迁移在真实用户机上直接抛 UNIQUE constraint failed。
        val file = context.getDatabasePath(dbName)
