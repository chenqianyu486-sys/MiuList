    @Test
    fun `custom task types round-trip and merge with the built-in ones`() = runBlocking {
        createVersion5Database()
        val db = openWithMigrations()
        try {
            val dao = db.customTaskTypeDao()
            assertEquals("升级用户不该凭空多出自定义类型", 0, dao.getAllOnce().size)

            val custom = CustomTaskType(
                id = "reading-notes",
                label = "读书笔记",
                colorHex = "#A6D6E4",
                inkHex = "#3F5F69",
                sortOrder = 1
            )
            dao.insert(
                CustomTaskTypeEntity(
                    id = custom.id,
                    label = custom.label,
                    colorHex = custom.colorHex,
                    inkHex = custom.inkHex,
                    sortOrder = custom.sortOrder
                )
            )
            assertEquals("读书笔记", dao.getAllOnce().single().label)

            // 内置 + 自定义合并成同一份选项列表，自定义排在后面
            val options = TaskTypes.options(listOf(custom))
            assertEquals(TaskType.entries.size + 1, options.size)
            assertTrue(options.take(TaskType.entries.size).none { it.isCustom })
            assertEquals("读书笔记", options.last().label)
            assertEquals("CUSTOM:reading-notes", options.last().key)

            // 用落库的 key 能反查回同一个类型
            assertEquals("读书笔记", TaskTypes.resolve(custom.key, listOf(custom))?.label)
            // 悬空 key 和空串都解析不出类型 —— 前者是删过类型的老数据，后者是主动留空
            assertNull(TaskTypes.resolve("CUSTOM:deleted", listOf(custom)))
            assertNull(TaskTypes.resolve("", listOf(custom)))

            // 删除后用它的那几条待办退化成「未分类」，而不是连待办一起消失
