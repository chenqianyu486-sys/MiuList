            assertEquals(
                TaskType.POST_CLASS.label,
                TaskTypes.resolve(byTitle.getValue("第 5 周作业").taskType, emptyList())?.label
            )
            // 老数据一条都不能少
            assertEquals(3, byTitle.size)
            assertTrue(db.customTaskTypeDao().getAllOnce().isEmpty())
        } finally {
            db.close()
        }
    }

