package com.example.data.repository

import android.content.Context
import androidx.test.core.app.ApplicationProvider
import com.example.data.di.AppContainer
import com.example.data.local.TaskEntity
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * 老用户的默认值：「一键生成待办」这个开关**默认关**，但**用过的人保持开启**。
 *
 * 升级上来的老用户如果一直在用一键生成，不该因为加了这个开关就突然失去那个入口；
 * 而全新安装（库里空着）的人默认得到轻量体验。
 *
 * 判据是**库里有没有带周次的待办**：只有生成引擎排出来的才带周次
 * （去重键就是「课程 + 类型 + 周次 + 周几」），手工加的没有周次。
 *
 * **不能拿 `isAutoGenerated` 当判据**：那一列的默认值就是 true，手工待办也是 true ——
 * 拿它当「生成过」的证据，等于所有人都会被判成用过。
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class QuickGenerateLegacyDefaultTest {

    private fun container(): AppContainer =
        AppContainer(ApplicationProvider.getApplicationContext<Context>())

    @After
    fun tearDown() {
        runBlocking { container().database.taskDao().clearTasks() }
    }

    private suspend fun seedTask(week: Int, dayOfWeek: Int) {
        container().database.taskDao().insertTask(
            TaskEntity(
                courseId = TaskEntity.UNLINKED_COURSE_ID,
                courseName = TaskEntity.UNLINKED_COURSE_NAME,
                courseCategory = "",
                courseColorHex = TaskEntity.UNLINKED_COLOR_HEX,
                title = "第 $week 周的活",
                taskType = "POST_CLASS",
                dueDateTimestamp = 1L,
                week = week,
                dayOfWeek = dayOfWeek
            )
        )
    }

    @Test
    fun `空库算没用过`() {
        runBlocking {
            assertFalse(
                "全新安装的设备默认走轻量体验",
                container().taskRepository.hasGeneratedWeekTasks()
            )
        }
    }

    @Test
    fun `只有手工待办算没用过`() {
        runBlocking {
            seedTask(week = 0, dayOfWeek = 0)

            assertFalse(
                "手工加的待办没有周次，不算用过一键生成",
                container().taskRepository.hasGeneratedWeekTasks()
            )
        }
    }

    @Test
    fun `有带周次的待办算用过`() {
        runBlocking {
            seedTask(week = 3, dayOfWeek = 2)

            assertTrue(
                "生成出来的待办带周次，说明这台设备用过一键生成",
                container().taskRepository.hasGeneratedWeekTasks()
            )
        }
    }
}
