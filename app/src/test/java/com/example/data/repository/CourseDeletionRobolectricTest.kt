package com.example.data.repository

import android.content.Context
import androidx.test.core.app.ApplicationProvider
import com.example.data.di.AppContainer
import com.example.data.local.CourseEntity
import com.example.data.local.CourseSlotEntity
import com.example.data.local.TaskEntity
import com.example.data.model.SlotWithWeeks
import com.example.data.model.STAR_MARKED
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

/**
 * 删课程对待办的影响。Robolectric + 真实 Room。
 *
 * 这一层要守住的是**待办是用户自己的数据**：删一门课只是让它上面的待办失去归属，
 * 不等于那些待办该跟着消失。改造前 `deleteCourse` 里的第一句就是
 * `taskDao.deleteTasksByCourseId(courseId)`，用户在课程弹层里点一次「删除课程」，
 * 写好的作业、正文、勾选状态、截止日期一并没了，而且没有任何确认弹层。
 *
 * 现在改成移入「未关联课程」（与整表替换 REPLACE 同一条路，见 `ScheduleImportService`）：
 * 课程行消失后不改写归属，待办就会指向一个已不存在的 id ——
 * 既不在任何课程下、也进不了「未关联课程」分组，等于凭空消失，比 DELETE 还隐蔽。
 */
@RunWith(RobolectricTestRunner::class)
// 用 SDK 34 而不是工程的 targetSdk 36：Robolectric 的 36 号沙箱要求 JDK 21，
// 本机构建环境固定是 JDK 17。这里验的是事务与待办归属，与 API 36 无关。
@Config(sdk = [34])
class CourseDeletionRobolectricTest {

    private fun container(): AppContainer =
        AppContainer(ApplicationProvider.getApplicationContext<Context>())

    /**
     * 收尾清空，理由同 `CategoryLinkageRobolectricTest` / `ScheduleTransferRobolectricTest`：
     * Robolectric 里 `AppDatabase` 是单例，**测试类之间共用同一个库文件**，
     * 本类留下的课程会让 `ExampleRobolectricTest` 的播种判据误判成「已经播好了」。
     *
     * 待办也要清：本类会往共享库里插待办，不清会漏到别的类里。
     */
    @After
    fun tearDown() {
        runBlocking { reset(container()) }
    }

    private suspend fun reset(c: AppContainer) {
        c.database.taskDao().clearTasks()
        c.courseRepository.clearAllCourses()
        c.settingsRepository.replaceAll(emptyList())
    }

    private suspend fun seedCourse(c: AppContainer, name: String): Long =
        c.courseRepository.saveCourseWithSlots(
            CourseEntity(
                name = name, category = "公共基础", teacher = "王教授",
                classroom = "教二-301", colorHex = "#93C5FD"
            ),
            listOf(
                SlotWithWeeks(
                    slot = CourseSlotEntity(courseId = 0, dayOfWeek = 1, startPeriod = 1, endPeriod = 2),
                    weeks = setOf(1, 2)
                )
            )
        )

    /** 一条挂在某门课下的待办，已勾选的那条要连完成时刻一起带上。 */
    private suspend fun seedTask(
        c: AppContainer,
        courseId: Long,
        courseName: String,
        title: String,
        completed: Boolean = false
    ): Long = c.database.taskDao().insertTask(
        TaskEntity(
            courseId = courseId,
            courseName = courseName,
            courseCategory = "公共基础",
            courseColorHex = "#93C5FD",
            title = title,
            description = "第 $title 页到第 ${title.length} 页",
            taskType = "POST_CLASS",
            dueDateTimestamp = 1_800_000_000_000L,
            dueDateString = "2027-01-15 23:59",
            priority = STAR_MARKED,
            isCompleted = completed,
            completedAt = if (completed) 1_800_000_100_000L else null,
            isAutoGenerated = false,
            week = 3,
            dayOfWeek = 4
        )
    )

    private suspend fun taskByTitle(c: AppContainer, title: String): TaskEntity =
        c.database.taskDao().getAllTasksOnce().first { it.title == title }

    // -------------------------------------------------------------- 核心承诺

    @Test
    fun `删课程不会吞掉挂在它上面的待办`() = runBlocking {
        val c = container()
        reset(c)
        val id = seedCourse(c, "高等数学")
        val taskId = seedTask(c, id, "高等数学", "习题 3.2")

        c.courseRepository.deleteCourse(id)

        val task = c.database.taskDao().getAllTasksOnce().single()
        assertEquals("待办行必须还在", taskId, task.id)
        assertEquals("习题 3.2", task.title)
    }

    /** 一条都不能少，也不多：课程没了就落进「未关联课程」，等用户重新决定挂到哪。 */
    @Test
    fun `被删课程的待办整体移入未关联课程`() = runBlocking {
        val c = container()
        reset(c)
        val id = seedCourse(c, "高等数学")
        seedTask(c, id, "高等数学", "习题 3.2")
        seedTask(c, id, "高等数学", "习题 3.3", completed = true)

        assertEquals("返回被移走的条数，好让界面如实告诉用户", 2, c.courseRepository.deleteCourse(id))

        val tasks = c.database.taskDao().getAllTasksOnce()
        assertEquals(2, tasks.size)
        assertTrue(tasks.all { it.courseId == TaskEntity.UNLINKED_COURSE_ID })
        assertTrue(tasks.all { it.courseName == TaskEntity.UNLINKED_COURSE_NAME })
        assertTrue(tasks.all { it.courseCategory == "" })
        assertTrue(
            "不换颜色的话，清单里会继续挂着已经不存在的课的配色",
            tasks.all { it.courseColorHex == TaskEntity.UNLINKED_COLOR_HEX }
        )
    }

    /** 归属改了，用户自己写的东西一个字都不许动。 */
    @Test
    fun `移入未关联只改归属不改待办内容`() = runBlocking {
        val c = container()
        reset(c)
        val id = seedCourse(c, "高等数学")
        seedTask(c, id, "高等数学", "习题 3.2")
        val before = taskByTitle(c, "习题 3.2")

        c.courseRepository.deleteCourse(id)

        val after = taskByTitle(c, "习题 3.2")
        assertEquals(before.title, after.title)
        assertEquals(before.description, after.description)
        assertEquals(before.taskType, after.taskType)
        assertEquals(before.dueDateTimestamp, after.dueDateTimestamp)
        assertEquals(before.dueDateString, after.dueDateString)
        assertEquals(before.priority, after.priority)
        assertEquals(before.isCompleted, after.isCompleted)
        assertEquals(before.completedAt, after.completedAt)
        assertEquals(before.isAutoGenerated, after.isAutoGenerated)
        assertEquals(before.week, after.week)
        assertEquals(before.dayOfWeek, after.dayOfWeek)
        assertEquals(before.createdAt, after.createdAt)
        assertFalse(after.isCompleted)
    }

    /** 已勾选的待办同样要保住完成时刻，不能因为课程没了就变回未完成。 */
    @Test
    fun `已完成的待办连完成时刻一起保留`() = runBlocking {
        val c = container()
        reset(c)
        val id = seedCourse(c, "高等数学")
        seedTask(c, id, "高等数学", "习题 3.3", completed = true)

        c.courseRepository.deleteCourse(id)

        val after = taskByTitle(c, "习题 3.3")
        assertTrue(after.isCompleted)
        assertEquals(1_800_000_100_000L, after.completedAt)
    }

    // -------------------------------------------------------------- 边界

    @Test
    fun `别的课程的待办不动`() = runBlocking {
        val c = container()
        reset(c)
        val deleted = seedCourse(c, "高等数学")
        val kept = seedCourse(c, "大学英语")
        seedTask(c, deleted, "高等数学", "习题 3.2")
        seedTask(c, kept, "大学英语", "背单词 Unit 5")

        c.courseRepository.deleteCourse(deleted)

        val keptTask = taskByTitle(c, "背单词 Unit 5")
        assertEquals(kept, keptTask.courseId)
        assertEquals("大学英语", keptTask.courseName)
        assertEquals("#93C5FD", keptTask.courseColorHex)
    }

    /** 本来就没挂课程的待办与课表无关，删课不该碰它们。 */
    @Test
    fun `本来就未关联的待办不受影响`() = runBlocking {
        val c = container()
        reset(c)
        val id = seedCourse(c, "高等数学")
        val free = c.database.taskDao().insertTask(
            TaskEntity(
                courseId = TaskEntity.UNLINKED_COURSE_ID,
                courseName = TaskEntity.UNLINKED_COURSE_NAME,
                courseCategory = "",
                courseColorHex = TaskEntity.UNLINKED_COLOR_HEX,
                title = "取快递",
                taskType = "CUSTOM:3",
                dueDateTimestamp = TaskEntity.NO_DUE_TIMESTAMP,
                dueDateString = ""
            )
        )

        assertEquals(0, c.courseRepository.deleteCourse(id))

        assertEquals(free, taskByTitle(c, "取快递").id)
    }

    @Test
    fun `课程没有待办时返回零`() = runBlocking {
        val c = container()
        reset(c)
        val id = seedCourse(c, "大学英语")

        assertEquals(0, c.courseRepository.deleteCourse(id))
    }

    // -------------------------------------------------------------- 该删的确实删了

    @Test
    fun `课程与它的时段确实被删掉`() = runBlocking {
        val c = container()
        reset(c)
        val id = seedCourse(c, "高等数学")
        seedTask(c, id, "高等数学", "习题 3.2")

        c.courseRepository.deleteCourse(id)

        assertNull(c.courseRepository.getCourseById(id))
        assertEquals("时段是课程聚合内的从属数据，要跟着走", 0, c.courseRepository.getAllSlotsOnce().size)
        assertEquals("开课周次由时段级联删除", 0, c.courseRepository.getAllSlotWeeksOnce().size)
    }
}
