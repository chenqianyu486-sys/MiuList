package com.example.data.source.zju

import com.example.data.local.CourseEntity
import com.example.data.local.TaskEntity
import com.example.data.model.TaskType
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * 学在浙大的一条待办 → MiuList 的待办草稿。
 *
 * 搬的是四样东西：名称、截止、备注、关联课程。
 * 关联课程**对不上就留空** —— 挂错课比不挂更糟。
 */
class CoursesTodoTaskDraftTest {

    private fun course(id: Long, name: String) = CourseEntity(
        id = id,
        name = name,
        category = "专业必修",
        teacher = "张老师",
        classroom = "教三 201",
        colorHex = "#93C5FD"
    )

    private fun item(
        id: String = "1",
        title: String = "第3章习题",
        courseName: String = "高等数学",
        dueTimestamp: Long? = 1793116740000L
    ) = CoursesTodoItem(
        id = id,
        title = title,
        courseName = courseName,
        dueTimestamp = dueTimestamp,
        dueFormatted = "10月25日 23:59",
        daysRemainingText = "2天后",
        isUrgent = false
    )

    private fun detail(
        description: String = "做完第 1-6 题，拍照上传。",
        attachments: List<Attachment> = listOf(Attachment("习题.pdf"))
    ) = CoursesTodoDetail(
        activityId = "1",
        title = "第3章习题",
        description = description,
        completionCriterion = "",
        attachments = attachments,
        dueTimestamp = 1793116740000L
    )

    @Test
    fun `名称来自学在浙大的作业名`() {
        val draft = buildCoursesTodoDraft(item(title = "第3章习题"), null, emptyList())
        assertEquals("第3章习题", draft.title)
    }

    @Test
    fun `截止时间搬过来`() {
        val draft = buildCoursesTodoDraft(item(), null, emptyList())
        assertEquals(1793116740000L, draft.dueDateTimestamp)
        assertTrue(draft.dueDateString.isNotBlank())
    }

    @Test
    fun `没有截止时间就不设截止`() {
        val draft = buildCoursesTodoDraft(item(dueTimestamp = null), null, emptyList())
        assertEquals(TaskEntity.NO_DUE_TIMESTAMP, draft.dueDateTimestamp)
        assertEquals("", draft.dueDateString)
    }

    @Test
    fun `备注装的是作业说明`() {
        val draft = buildCoursesTodoDraft(item(), detail(description = "做完第 1-6 题。"), emptyList())
        assertTrue(draft.description.contains("做完第 1-6 题。"))
    }

    @Test
    fun `附件名字也进备注`() {
        val draft = buildCoursesTodoDraft(
            item(),
            detail(description = "", attachments = listOf(Attachment("习题.pdf"), Attachment("封面.docx"))),
            emptyList()
        )
        assertTrue(draft.description.contains("习题.pdf"))
        assertTrue(draft.description.contains("封面.docx"))
    }

    @Test
    fun `课程对得上就关联上`() {
        val courses = listOf(course(7L, "高等数学"))
        val draft = buildCoursesTodoDraft(item(), detail(), courses)
        assertEquals(7L, draft.courseId)
        assertEquals("高等数学", draft.courseName)
    }

    @Test
    fun `课程名只是格式不同时也关联上`() {
        // 「大学物理（下）」对「大学物理」：归一化之后是同一门课，
        // 关联课程就是这一门，编辑弹层的默认关联课程也是它。
        val courses = listOf(course(7L, "大学物理"))
        val draft = buildCoursesTodoDraft(item(courseName = "大学物理（下）"), detail(), courses)
        assertEquals(7L, draft.courseId)
        assertEquals("大学物理", draft.courseName)
    }

    @Test
    fun `相似度不够仍然不关联`() {
        val courses = listOf(course(7L, "大学化学"))
        val draft = buildCoursesTodoDraft(item(courseName = "大学物理"), detail(), courses)
        assertEquals(TaskEntity.UNLINKED_COURSE_ID, draft.courseId)
    }

    @Test
    fun `课程对不上就留空`() {
        val courses = listOf(course(7L, "大学物理"))
        val draft = buildCoursesTodoDraft(item(courseName = "马克思主义基本原理"), detail(), courses)
        assertEquals(TaskEntity.UNLINKED_COURSE_ID, draft.courseId)
        assertEquals(TaskEntity.UNLINKED_COURSE_NAME, draft.courseName)
    }

    @Test
    fun `草稿还没落库所以id是0`() {
        // id == 0 是编辑弹层区分「新建」和「编辑」的判据。
        assertEquals(0L, buildCoursesTodoDraft(item(), detail(), emptyList()).id)
    }

    @Test
    fun `不是自动生成的是用户自己加的`() {
        assertFalse(buildCoursesTodoDraft(item(), detail(), emptyList()).isAutoGenerated)
    }

    @Test
    fun `归到课后作业这一类`() {
        assertEquals(TaskType.POST_CLASS.name, buildCoursesTodoDraft(item(), detail(), emptyList()).taskType)
    }
}
