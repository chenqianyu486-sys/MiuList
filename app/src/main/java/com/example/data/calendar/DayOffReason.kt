package com.example.data.calendar

/**
 * 这一天为什么不上课。
 *
 * 周课表要区分这几种「空列」，因为它们对用户的含义完全不同：
 * 「停课」和「让出课」是校历上明确记着的调休，空列里**本来是有课的**；
 * 「周末」和「学期外」则是本来就没课。前者不标出来，用户会以为自己的课被弄丢了。
 *
 * ## 硬闸门 vs 软闸门
 *
 * 这里最要紧的分界是**放假停课**与**周末**不是一回事：
 *
 * | 原因 | 性质 | 那天一定没课吗 |
 * |------|------|----------------|
 * | [NO_CLASS] | 硬 | 是 —— 校历明确记的停课 |
 * | [VACATED] | 硬 | 是 —— 课被搬到别的日子去了 |
 * | [OUT_OF_TERM] | 硬 | 是 —— 这一天根本不属于这个学期 |
 * | [WEEKEND] | **软** | **不一定** —— 周末是「默认没课」，不是「一定没课」 |
 *
 * 周末为什么是软的：用户完全可能把课排在周六（竞赛集训、实验、辅导班、
 * 周末兼职的课）。他自己排的课就该认，「周六不上课」只是**常识**，
 * 不是**校历规定**。于是周末到底有没有课，得连排课数据一起看才知道 ——
 * 判定入口是 [ScheduleResolver.slotsOn]，它只在周末**确实排了课**时才出课。
 *
 * 反过来说，界面上的文案也不能混：周六显示「今天停课」是在说一件根本没发生的事，
 * 放假停课才配叫「停课」。见 `todayEmptyStateLabel`。
 */
enum class DayOffReason {
    /** 校历里明确记的停课日（放假）。 */
    NO_CLASS,

    /** 调休让出课的那一天：这天的课被搬到别的日子去了。 */
    VACATED,

    /** 普通周末，且没有标补课。**软**理由：排了课就有课。 */
    WEEKEND,

    /** 落在学期范围之外（开学前 / 学期结束后）。 */
    OUT_OF_TERM
}

/**
 * 这些原因里，哪些是**硬**闸门（那天一定没课，不管用户排了什么）。
 *
 * 周末不在其中 —— 这是「周末排的课要显示」与「放假停课要显示」能同时成立的前提。
 */
internal fun DayOffReason.blocksAllClasses(): Boolean = when (this) {
    DayOffReason.NO_CLASS, DayOffReason.VACATED, DayOffReason.OUT_OF_TERM -> true
    DayOffReason.WEEKEND -> false
}
