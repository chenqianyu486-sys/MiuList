package com.example.data.calendar

/**
 * 手上这份校历是**从哪儿来的**。
 *
 * 界面上必须显示它 —— 用户凭什么相信弹层顶部那一块「官方校历」，唯一的依据
 * 就是它能说清楚自己读的是远程、缓存还是内置。三种来源的可信度并不相同：
 * 远程是刚拉的最新值，缓存是"上次确实拉到过"，内置只保证"随版本发出来时是对的"。
 */
enum class CalendarOrigin {
    /** 刚从远程托管拉到。 */
    REMOTE,

    /** 本机缓存里上次成功拉到的那份原文。断网也能用。 */
    CACHED,

    /** 随 App 发出来的兜底数据。 */
    BUNDLED
}
