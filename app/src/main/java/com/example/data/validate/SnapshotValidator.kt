package com.example.data.validate

import com.example.data.codec.ScheduleBundle
import com.example.data.codec.TaskBundle
import com.example.data.codec.TaskRuleBundle
import com.example.data.codec.TaskTypeBundle
import com.example.data.model.TaskStar
import com.example.data.model.isValidHexColor

/** v3 三块用户数据的校验结果。 */
data class ValidatedSnapshot(
    /** 通过校验、可直接落库的待办。空 uid 的已被剔除。 */
    val tasks: List<TaskBundle>,
    val taskTypes: List<TaskTypeBundle>,
    val taskRules: List<TaskRuleBundle>,
    val issues: List<ImportIssue>
) {
    companion object {
        /** 三块整体缺席 —— 浙大同步产出的文档、zju-ical 的 `config.json` 都是这种形状。 */
        val EMPTY = ValidatedSnapshot(emptyList(), emptyList(), emptyList(), emptyList())
    }
}

/**
 * v3 用户数据（待办 / 自定义分类 / 生成规则）的归一化与校验。
 *
 * **刻意不认识 JSON**：只吃 [ScheduleBundle]、只吐 [ValidatedSnapshot]，
 * 与 [ScheduleBundleValidator] 同一套分层。解析层负责搬，这里负责判。
 *
 * ## 这里的判据与课表那边不同
 *
 * 课表那边判的是「这份数据自相矛盾吗」。这里判的是「**这条能不能参与合并**」——
 * 合并靠 uid 认人，所以 uid 缺失不是「信息不全」，而是**这条待办没有身份**。
 *
 * 因此空 uid 的条目一律**剔除并记 issue，绝不现场生成一个**。
 * 现场生成看着像修复，实际后果严重得多：同一份文件每导入一次就多出一条待办，
 * 而用户看到的是「同步了一下，待办变多了」。剔除 + 报出来，用户至少知道发生了什么。
 *
 * 刻意**不整档失败**：三块全空是浙大同步产出的合法形状。
 */
class SnapshotValidator {

    fun validate(raw: ScheduleBundle): ValidatedSnapshot {
        if (raw.hasNoUserData) return ValidatedSnapshot.EMPTY

        val issues = mutableListOf<ImportIssue>()
        val types = validateTaskTypes(raw.taskTypes, issues)
        val tasks = validateTasks(raw.tasks, issues)
        val rules = validateTaskRules(raw.taskRules, issues)
        return ValidatedSnapshot(tasks, types, rules, issues)
    }

    // ------------------------------------------------------------------ 待办

    private fun validateTasks(rows: List<TaskBundle>, issues: MutableList<ImportIssue>): List<TaskBundle> {
        val out = mutableListOf<TaskBundle>()
        var withoutUid = 0
        // 同一份文件里重复的 uid：后出现的算无效。真的重复说明文件被拼过，
        // 而按 uid 合并时两者会打成一团，最后写进去的是哪一条完全看写入顺序。
        val seen = mutableSetOf<String>()

        for (row in rows) {
            val uid = row.syncUid?.takeIf { it.isNotBlank() }
            if (uid == null) {
                withoutUid++
                continue
            }
            if (!seen.add(uid)) {
                issues += ImportIssue("待办", "同步身份重复的条目已忽略：${row.title ?: uid}")
                continue
            }
            if (row.title.isNullOrBlank()) {
                issues += ImportIssue("待办", "没有标题，已忽略：$uid")
                continue
            }
            out += normalize(row, uid)
        }
        if (withoutUid > 0) {
            issues += ImportIssue(
                "待办",
                "$withoutUid 条待办缺少同步身份，已忽略。" +
                    "这是升级后尚未补齐的旧数据，在应用里打开一次就会自动补上。"
            )
        }
        return out
    }

    private fun normalize(row: TaskBundle, uid: String): TaskBundle {
        // 星标归一到两态：旧文件里的 HIGH / MEDIUM / LOW 按 TaskStar 的兼容表读进来，
        // 写回时一律落成 STAR / 空串（见 TaskStar 的说明）。
        val star = TaskStar.isMarked(row.priority.orEmpty())
        return row.copy(
            syncUid = uid,
            priority = TaskStar.encode(star),
            taskType = row.taskType.orEmpty(),
            description = row.description.orEmpty(),
            // createdAt / updatedAt 缺省时用 0，合并侧会把 0 当「比谁都早」处理，
            // 于是这条待办保留本机版本 —— 对一份没说清楚时间的老文件，
            // 「不动」比「覆盖」安全。
            updatedAt = row.updatedAt ?: 0L,
            isCompleted = row.isCompleted ?: false,
            isAutoGenerated = row.isAutoGenerated ?: false,
            week = row.week ?: 0,
            dayOfWeek = row.dayOfWeek ?: 0
        )
    }

    // ------------------------------------------------------------------ 自定义分类

    private fun validateTaskTypes(
        rows: List<TaskTypeBundle>,
        issues: MutableList<ImportIssue>
    ): List<TaskTypeBundle> {
        val out = mutableListOf<TaskTypeBundle>()
        val seen = mutableSetOf<String>()
        for (row in rows) {
            val id = row.id?.takeIf { it.isNotBlank() }
            val label = row.label?.takeIf { it.isNotBlank() }
            when {
                id == null -> {
                    issues += ImportIssue("待办分类", "缺少身份，已忽略：${row.label ?: "未命名"}")
                    continue
                }
                label == null -> {
                    issues += ImportIssue("待办分类", "没有名称，已忽略：$id")
                    continue
                }
                !seen.add(id) -> {
                    issues += ImportIssue("待办分类", "身份重复的条目已忽略：$label")
                    continue
                }
            }
            // 配色非法就退回内置配色里的一对（雾灰），而不是原样写进去：
            // 一个空 colorHex 会让 chip 变成透明条，而用户看不出「这里的颜色没导过来」。
            val valid = row.colorHex != null && isValidHexColor(row.colorHex) &&
                row.inkHex != null && isValidHexColor(row.inkHex)
            out += if (valid) {
                row.copy(id = id, label = label)
            } else {
                issues += ImportIssue("待办分类", "配色无法解析，已退回默认色：$label")
                row.copy(
                    id = id,
                    label = label,
                    colorHex = FALLBACK_TYPE_COLOR,
                    inkHex = FALLBACK_TYPE_INK
                )
            }
        }
        return out
    }

    // ------------------------------------------------------------------ 生成规则

    private fun validateTaskRules(
        rows: List<TaskRuleBundle>,
        issues: MutableList<ImportIssue>
    ): List<TaskRuleBundle> {
        val out = mutableListOf<TaskRuleBundle>()
        val seen = mutableSetOf<String>()
        for (row in rows) {
            val courseKey = row.courseKey?.takeIf { it.isNotBlank() }
            val taskType = row.taskType?.takeIf { it.isNotBlank() }
            if (courseKey == null || taskType == null) {
                issues += ImportIssue("生成规则", "缺少课程或类型，已忽略：${row.taskType ?: "未知"}")
                continue
            }
            // 主键就是这两列，重复意味着同一格被写了两次。
            if (!seen.add("$courseKey|$taskType")) {
                issues += ImportIssue("生成规则", "同一门课同一类型的重复规则已忽略：$taskType")
                continue
            }
            out += row.copy(courseKey = courseKey, taskType = taskType)
        }
        return out
    }

    private companion object {
        // 与 TaskTypePalettes 的「雾灰」同一对。校验器不该依赖 TaskTypePalettes：
        // 那里是「让用户挑」的候选集，而这里是「挑不出来时」的兜底，两者会各自演进。
        const val FALLBACK_TYPE_COLOR = "#D2D8DE"
        const val FALLBACK_TYPE_INK = "#565D64"
    }
}
