package com.example.data.sync.web

import com.example.data.local.TaskEntity
import com.example.data.model.TaskStar
import com.example.data.repository.CourseRepository
import com.example.data.repository.TaskRepository

/**
 * 待办写回的口子。抽成接口是为了让 [WebSyncApi] 能在**没有 Room** 的地方测 ——
 * 接口层的测试不该为了验证一个路由去建一整个数据库。
 */
interface TaskWriter {
    suspend fun create(patch: WebTaskPatchDto): TaskWriteService.Result
    suspend fun update(syncUid: String, patch: WebTaskPatchDto): TaskWriteService.Result
    suspend fun delete(syncUid: String): TaskWriteService.Result
}

/**
 * 网页端往回写的改动。
 *
 * ## 冲突怎么办
 *
 * 手机是唯一的数据源，但它同时可能有**好几个**浏览器开着（电脑一个、平板一个）。
 * 两边都改同一条待办时，谁说了算？
 *
 * 这里用的是**乐观并发**：网页端提交时带上它**看到的那一版**的 `updatedAt`
 * （[WebTaskPatchDto.baseUpdatedAt]），服务端发现本地已经比这更新，
 * 就**拒绝**这次写入并回 409 + 当前值 —— 网页端据此提示「这条已经变了」，
 * 而不是默默覆盖掉用户在手机上刚做的改动。
 *
 * 不用「最后写入者赢」是因为那会让**旧标签页**覆盖新数据：
 * 一个开着两小时的网页标签页，点一下勾选，就把手机上五分钟前的改动冲掉了。
 *
 * ## 为什么 `updatedAt` 由服务端盖
 *
 * 两台设备的时钟可能差几分钟。用**客户端**的时间戳做仲裁，
 * 慢的那台永远赢不了 —— 它的每一次改动都会被当成「旧的」。
 * 服务端盖章则保证库里那一列是同一把尺子量出来的。
 */
class TaskWriteService(
    private val taskRepo: TaskRepository,
    private val courseRepo: CourseRepository,
    private val clock: () -> Long = { System.currentTimeMillis() },
) : TaskWriter {

    override suspend fun create(patch: WebTaskPatchDto): Result {
        val title = patch.title?.trim().orEmpty()
        if (title.isEmpty()) return Result.Invalid("标题不能为空")
        if (title.length > MAX_TITLE) return Result.Invalid("标题太长了（上限 $MAX_TITLE 字）")

        val course = patch.courseKey
            ?.takeIf { it.isNotBlank() }
            ?.let { key -> courseRepo.getByDedupeKey(key).firstOrNull() }

        val entity = TaskEntity(
            courseId = course?.id ?: TaskEntity.UNLINKED_COURSE_ID,
            courseName = course?.name ?: TaskEntity.UNLINKED_COURSE_NAME,
            courseCategory = course?.category.orEmpty(),
            courseColorHex = course?.colorHex ?: TaskEntity.UNLINKED_COLOR_HEX,
            title = title,
            description = patch.description.orEmpty(),
            taskType = patch.taskType.orEmpty(),
            startTimeTimestamp = 0L,
            dueDateTimestamp = patch.dueDateTimestamp ?: TaskEntity.NO_DUE_TIMESTAMP,
            dueDateString = patch.dueDateString.orEmpty(),
            priority = TaskStar.encode(TaskStar.isMarked(patch.priority.orEmpty())),
            isCompleted = patch.isCompleted ?: false,
            completedAt = if (patch.isCompleted == true) clock() else null,
            // 网页端建的待办一律是手动的：不占自动生成的坑，
            // 也不参与「同课程 + 同类型 + 同周次 + 同周几」那条去重规则。
            isAutoGenerated = false,
            week = 0,
            dayOfWeek = 0,
        )

        taskRepo.insertTask(entity)
        val saved = taskRepo.getAllTasksOnce().lastOrNull { it.title == title && it.syncUid.isNotBlank() }
            ?: return Result.Invalid("写库之后没找到这条待办")
        return Result.Ok(
            saved.toWebDto(
                courseKey = course?.dedupeKey.orEmpty(),
                taskTypeLabel = "",
            )
        )
    }

    /** 改一条待办。 */
    override suspend fun update(syncUid: String, patch: WebTaskPatchDto): Result {
        val local = taskRepo.getBySyncUid(syncUid) ?: return Result.NotFound("没有这条待办")
        val localDto = local.toWebDto(courseKey = "", taskTypeLabel = "")

        val base = patch.baseUpdatedAt
        if (base != null && base > 0 && base < local.updatedAt) {
            return Result.Conflict(localDto, "这条待办在手机上已经改过了")
        }

        val next = local.copy(
            title = patch.title?.trim()?.takeIf { it.isNotEmpty() } ?: local.title,
            description = patch.description ?: local.description,
            taskType = patch.taskType ?: local.taskType,
            priority = patch.priority?.let { TaskStar.encode(TaskStar.isMarked(it)) } ?: local.priority,
            isCompleted = patch.isCompleted ?: local.isCompleted,
            completedAt = when {
                patch.isCompleted == null -> local.completedAt
                patch.isCompleted -> clock()
                else -> null
            },
            dueDateTimestamp = patch.dueDateTimestamp ?: local.dueDateTimestamp,
            dueDateString = patch.dueDateString ?: local.dueDateString,
        )

        taskRepo.updateTask(next)
        val saved = taskRepo.getBySyncUid(syncUid) ?: next
        return Result.Ok(saved.toWebDto(courseKey = "", taskTypeLabel = ""))
    }

    /** 删一条待办。 */
    override suspend fun delete(syncUid: String): Result {
        val local = taskRepo.getBySyncUid(syncUid) ?: return Result.NotFound("没有这条待办")
        taskRepo.deleteTask(local)
        return Result.Ok(local.toWebDto(courseKey = "", taskTypeLabel = ""))
    }

    /** 写入结果。 */
    sealed interface Result {
        data class Ok(val task: WebTaskDto) : Result
        data class NotFound(val message: String) : Result
        data class Conflict(val current: WebTaskDto, val message: String) : Result
        data class Invalid(val message: String) : Result
    }

    companion object {
        const val MAX_TITLE = 200
    }
}
