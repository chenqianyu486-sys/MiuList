/**
 * 局域网同步的线上格式（协议版本 1）。
 *
 * ## 三条设计约定
 *
 * 1. **时间一律用服务端算好的字符串。** `today` / `dueDateString` / `timeText`
 *    都在 App 时区（Asia/Shanghai）算完再发出去，网页端**不做任何时区换算** ——
 *    否则浏览器在 GMT 机器上会把「今天 23:59 截止」显示成明天，
 *    而手机上的 App 界面明明写的是今天。
 *
 * 2. **身份用 `syncUid`，不用本机 id。** 待办在两台设备上各有自己的自增 id，
 *    写进同步载荷等于把一端的主键强加给另一端。`syncUid` 是 UUID，
 *    创建时随机生成、此后不变（见 `TaskEntity.syncUid`）。
 *
 * 3. **时间是「后写覆盖」的仲裁依据。** `updatedAt` 由**服务端**盖章，
 *    网页端提交时带的是它看到的那个版本（`baseUpdatedAt`），
 *    用来发现「你在改一份已经过期的数据」。
 */

/** 协议版本。网页端按它判断能不能连。 */
const val WEB_SYNC_PROTOCOL = 1

/**
 * 同步方向。
 *
 * **从「执行方」的视角说**：执行方是真正去做这次同步的那一端。
 *
 * - [PULL] —— 执行方去另一端拉（另一端 → 执行方）。
 * - [PUSH] —— 执行方把自己的推给另一端（执行方 → 另一端）。
 * - [MERGE] —— 两边合并成一份。
 *
 * 手机发 `sync-request` 给网页端时，方向也是按**网页端**（执行方）说的：
 * 手机想「把手机数据推给网页端」，发的就是 [PULL]。
 */
enum class SyncDirection(val wire: String) {
    PULL("pull"),
    PUSH("push"),
    MERGE("merge");

    companion object {
        fun of(raw: String?): SyncDirection =
            entries.firstOrNull { it.wire.equals(raw, ignoreCase = true) } ?: MERGE
    }
}

@JsonClass(generateAdapter = true)
data class WebSnapshotDto(
    val protocol: Int = WEB_SYNC_PROTOCOL,
    /** 数据版本号。每次库里有变化就 +1，网页端用它判断自己是不是最新。 */
    val revision: Long = 0,
    val generatedAt: Long = 0,
    /** 今天的日期，`YYYY-MM-DD`，服务端时区。 */
    val today: String = "",
    /** 1=周一 … 7=周日。 */
    val weekday: Int = 0,
    val deviceName: String = "",
    val appVersion: String = "",
    /**
     * 这份快照里**最新的一次编辑**发生在什么时候（epoch 毫秒）。
     *
     * 手动选同步方向时，界面要拿它告诉用户「这一份是几点改的」——
     * 用户判断该往哪边同步，靠的就是这个时间，而不是「谁的条数多」。
     *
     * 没有改动时是 0。
     */
    val latestEditAt: Long = 0L,
    /**
     * App 时区相对 UTC 的偏移分钟数（Asia/Shanghai = 480）。
     *
     * 网页端渲染「最后编辑时间」必须用它，而**不能用浏览器本地时区** ——
     * 两台设备的时区设置可能不同，用户看到「本页 05:14 · 手机 21:14」
     * 会以为差了 16 小时，而不是同一时刻的两种写法。
     */
    val utcOffsetMinutes: Int = 480,
    /**
     * 这份快照里的课程是不是**有效内容**。
     *
     * false = 「这一端还没拿到过课程」，而不是「这一端没有课程」。
     * 少了这个标记，网页端第一次推送（它的课程块是空的）会把手机上的
     * 整个课表清空 —— 而那正是「刚打开网页端就点同步」最容易踩的坑。
     */
    val hasCourses: Boolean = false,
    /** 同上：考试。 */
    val hasExams: Boolean = false,
    /** 同上：自定义分类。 */
    val hasTaskTypes: Boolean = false,
    val tasks: List<WebTaskDto> = emptyList(),
    val taskTypes: List<WebTaskTypeDto> = emptyList(),
    val courses: List<WebCourseDto> = emptyList(),
    val exams: List<WebExamDto> = emptyList(),
    /** 今天实际要上的课（已按开课周次、停课、补课筛过）。 */
    val todayCourses: List<WebTodayCourseDto> = emptyList(),
    /**
     * 周课表：网页端那张栅格要的全部数据。
     *
     * **null = 这一端还没有周课表**（老版本 App，或课表还没生成过）。
     * 网页端据此把「周视图」这一档藏起来，而不是画一张空表。
     */
    val timetable: WebTimetableDto? = null,
    /**
     * **原始校历**（学期 / 调休 / 作息）。
     *
     * 周课表是**算好的结果**，网页端只画；而这一块是**规则本身** ——
     * 网页端显示用不到它，但**导出备份要靠它**：
     * 有了它，网页端导出的 JSON 才是一份完整的「整机快照」，
     * 而不是「一堆待办 + 一张画好的表」。
     *
     * null = 手机那边还没有校历（老版本 App）。
     */
    val calendar: WebCalendarDto? = null,
)

