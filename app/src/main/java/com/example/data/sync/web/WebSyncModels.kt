/** 「今天」与「现在」都以 App 时区为准，绝不用设备时区。 */
internal fun todayString(): String = EpochDays.format(EpochDays.today())

/** 此刻是北京时间的第几分钟。 */
internal fun minuteOfDayNow(): Int {
    val cal = AppZone.calendar()
    return cal.get(java.util.Calendar.HOUR_OF_DAY) * 60 + cal.get(java.util.Calendar.MINUTE)
}

/** 星标的两种取值。别在别处拼字符串。 */
internal fun starLabel(marked: Boolean): String = TaskStar.encode(marked)
