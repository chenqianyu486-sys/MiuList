package com.example.data.local

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.example.data.model.STAR_UNMARKED

@Entity(
    tableName = "tasks",
    // 故意不声明到 courses 的外键：
    // 「不关联课程」用 courseId = 0 表示（见 UNLINKED_COURSE_ID），
    // 外键会在每次保存未关联待办时抛 SQLiteConstraintException——courses 表里没有 id=0 的行。
    // 去掉外键不影响删课程的行为：CourseTodoRepository.deleteCourse() 本来就显式先删待办和时段。
    indices = [
        Index(value = ["courseId"]),
        Index(value = ["dueDateTimestamp"]),
        Index(value = ["startTimeTimestamp"]),
        Index(value = ["isCompleted"]),
        // 自动生成的待办按「同课程 + 同类型 + 同周次 + 同周几」去重，
        // 这个四元组是每次生成都要跑的查询，热路径上必须有索引。
        Index(value = ["courseId", "taskType", "week", "dayOfWeek"])
    ]
)
data class TaskEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val courseId: Long,
    val courseName: String,
    val courseCategory: String,
    val courseColorHex: String,
    val title: String,
    val description: String = "",
    /**
     * 类型原样字符串：内置存枚举名，自定义存 `CUSTOM:<id>`，**留空存空串**。
     * 解析见 `com.example.data.model.TaskTypes.resolve`。
     */
    val taskType: String,
    val startTimeTimestamp: Long = 0L, // Course start time / task start time
    val startTimeString: String = "", // e.g. "周一 08:00 (第1-2节)"
    /**
     * 截止时刻，或 [NO_DUE_TIMESTAMP] 表示「不设截止」。
     *
     * 同样刻意用哨兵而不是可空列：这一列上有索引（排序、热路径），
     * 改成可空既要多写一次迁移，又会让所有 `dueDateTimestamp` 的读点都要判空。
     * 哨兵选 [Long.MIN_VALUE] 而不是 0——0 是 1970 年，会被「已逾期」的判断吃掉，
     * 一条没写截止的待办在界面上会显示成逾期了 56 年。
     */
    val dueDateTimestamp: Long,
    val dueDateString: String = "", // e.g. "2026-10-12 23:59"，无截止时为空
    /**
     * 星标。只有两种状态，语义见 `TaskStar`：`STAR` = 标星，空串 = 没标星。
     *
     * 列名沿用旧的 `priority`，不迁 schema——这一列的语义从三级收成两态，
     * 旧值 `HIGH/MEDIUM/LOW` 由 `TaskStar.isMarked` 兼容读，用户下次保存即归一。
     */
    val priority: String = STAR_UNMARKED,
    val isCompleted: Boolean = false,
    val completedAt: Long? = null,
    val isAutoGenerated: Boolean = true,
    val generatedDate: String? = null, // e.g. "2026-10-12"，仅作溯源显示，去重不再依赖它
    /**
     * 归属的周次（1 起）。0 = 无周次概念（手工待办、未配置校历时生成的）。
     *
     * 和 [dayOfWeek] 一起构成自动生成待办的去重键：
     * 「同课程 + 同类型 + 同周次 + 同周几」已存在就不再生成一遍。
     *
     * [defaultValue] 必须显式声明：`MIGRATION_4_5` 用
     * `ALTER TABLE tasks ADD COLUMN week INTEGER NOT NULL DEFAULT 0` 加这一列，
     * Room 校验老库时会拿实体上声明的默认值去对（见 `CourseEntity.dedupeKey` 的同类说明）。
     */
    @ColumnInfo(defaultValue = "0")
    val week: Int = 0,
    /** 归属的星期几（1 = 周一 … 7 = 周日）。0 = 未指定。语义同 [week]。 */
    @ColumnInfo(defaultValue = "0")
    val dayOfWeek: Int = 0,
    val createdAt: Long = System.currentTimeMillis()
) {
    companion object {
        /**
         * 「不关联课程」的哨兵。
         *
         * `courseId` 是非空列且带 `ON DELETE CASCADE` 外键指向 courses，
         * 改成可空要么动 schema、要么失去外键，两条路都会牵连已有数据。
         * courses 的 id 是 AUTOINCREMENT，**永远不会是 0**，所以用 0 表示「无关联」是安全的：
         * 删课程不会误伤它，它也不会在课程删除时被级联抹掉。
         */
        const val UNLINKED_COURSE_ID = 0L
        const val UNLINKED_COURSE_NAME = "未关联"
        const val UNLINKED_COLOR_HEX = "#C9D0D8"

        /** 「不设截止」的哨兵。理由见 [dueDateTimestamp]。 */
        const val NO_DUE_TIMESTAMP = Long.MIN_VALUE

        fun isUnlinked(task: TaskEntity) = task.courseId == UNLINKED_COURSE_ID

        /** 是否设了截止。没设的待办不参与任何逾期判断，也不显示 ddl。 */
        fun hasDue(task: TaskEntity) = task.dueDateTimestamp != NO_DUE_TIMESTAMP
    }
}
