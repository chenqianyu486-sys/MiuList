package com.example.data.local

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey

@Entity(
    tableName = "tasks",
    foreignKeys = [
        ForeignKey(
            entity = CourseEntity::class,
            parentColumns = ["id"],
            childColumns = ["courseId"],
            onDelete = ForeignKey.CASCADE
        )
    ],
    indices = [
        Index(value = ["courseId"]),
        Index(value = ["dueDateTimestamp"]),
        Index(value = ["startTimeTimestamp"]),
        Index(value = ["isCompleted"])
    ]
)
data class TaskEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Long = 0,
    val courseId: Long,
    val courseName: String,
    val courseCategory: String,
    val courseColorHex: String,
    val title: String,
    val description: String = "",
    val taskType: String, // PRE_STUDY, POST_CLASS, LAB_REPORT, REVIEW, CUSTOM
    val startTimeTimestamp: Long = 0L, // Course start time / task start time
    val startTimeString: String = "", // e.g. "周一 08:00 (第1-2节)"
    val dueDateTimestamp: Long,
    val dueDateString: String, // e.g. "2026-10-12 23:59"
    val estimatedMinutes: Int = 45,
    val priority: String = "MEDIUM", // HIGH, MEDIUM, LOW
    val isCompleted: Boolean = false,
    val completedAt: Long? = null,
    val isAutoGenerated: Boolean = true,
    val generatedDate: String? = null, // e.g. "2026-10-12" to avoid duplicate generation
    val createdAt: Long = System.currentTimeMillis()
)
