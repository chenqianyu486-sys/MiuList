package com.example.data.codec

import com.squareup.moshi.JsonClass

/**
 * v3 新增的三块的 Moshi DTO。
 *
 * **刻意与 [ScheduleDtos] 分文件**。那个文件的契约是「`calendar` 块与 zju-ical
 * `configs/config.json` 逐字段同名同义」，好让那份 config.json 本身就能当一份
 * 「只有 calendar 的文档」直接导入；把待办、分类、生成规则塞进去会稀释那条约定，
 * 而这三块与 zju-ical 毫无关系。
 *
 * 全部字段可空且带默认值：**缺整块、缺字段都只是降级，不是整档失败**。
 * 与 v2 已有的判据一致 —— 一份别人手写、字段写得怪的文档不该被整份作废。
 */

/**
 * 一条待办。
 *
 * [syncUid] 与 [courseKey] 一律声明成 `String?`（不用 `Any?`、不挂 `@JsonQualifier`）：
 * `SlotDto.weeks` 那种「先声明成 `Any?` 再说」的写法在这里没有任何收益 ——
 * 这两个字段的类型本来就是确定的，而 Moshi 的 `Builder.add(Object)` 不认裸的
 * `JsonAdapter`，挂 `@JsonQualifier` 反而会让 KSP 阶段的 codegen 直接报
 * `Error preparing`。
 */
@JsonClass(generateAdapter = true)
data class TaskDto(
    val syncUid: String? = null,
    /** 关联课程的自然键，不是本机 courseId。null = 未关联课程。 */
    val courseKey: String? = null,
    val title: String? = null,
    val description: String? = null,
    val taskType: String? = null,
    val startTimeTimestamp: Long? = null,
    val dueDateTimestamp: Long? = null,
    val startTimeString: String? = null,
    val dueDateString: String? = null,
    val priority: String? = null,
    val isCompleted: Boolean? = null,
    val completedAt: Long? = null,
    val isAutoGenerated: Boolean? = null,
    val generatedDate: String? = null,
    val week: Int? = null,
    val dayOfWeek: Int? = null,
    val createdAt: Long? = null,
    val updatedAt: Long? = null
)

/** 用户新建的待办分类。 */
@JsonClass(generateAdapter = true)
data class TaskTypeDto(
    val id: String? = null,
    val label: String? = null,
    val colorHex: String? = null,
    val inkHex: String? = null,
    val sortOrder: Int? = null
)

/** 课程 × 类型的生成规则。课程用自然键表达，与 [TaskDto.courseKey] 同理。 */
@JsonClass(generateAdapter = true)
data class TaskRuleDto(
    val courseKey: String? = null,
    val taskType: String? = null,
    val cadence: String? = null,
    val dueOffsetDays: Int? = null,
    val dueBeforeMinutes: Int? = null
)

// ------------------------------------------------------------------ Bundle ↔ DTO

