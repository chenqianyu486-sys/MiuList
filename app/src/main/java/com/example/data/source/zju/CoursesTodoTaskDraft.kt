package com.example.data.source.zju

import com.example.data.calendar.AppZone
import com.example.data.local.CourseEntity
import com.example.data.local.TaskEntity
import com.example.data.model.TaskType

/**
 * 把学在浙大的一条待办，变成 MiuList 里的一条待办**草稿**。
 *
 * 草稿不是待办：它 id = 0，还没落库，要用户在编辑弹层里过一眼再存。
 *
 * ## 字段怎么搬
 *
 * | 学在浙大 | MiuList 待办 |
 * |---|---|
 * | 作业名 | 名称 |
 * | 截止时间 | ddl |
 * | 作业说明 + 附件清单 | 备注 |
 * | 课程名 | 关联课程（**对不上就留空**） |
 *
 * ## 为什么课程对不上就留空
 *
 * 见 [matchCourse]：挂错课程比不挂更糟 —— 那会让这条作业
 * 出现在一门不相干的课的时间线里，而它根本不是那门课的作业。
 *
 * 关联上的这门课会一路带到编辑弹层：草稿的 courseId 就是编辑弹层的默认关联课程，
 * 用户不用在滚筒里再选一次（想换也能换）。
 */
fun buildCoursesTodoDraft(
    item: CoursesTodoItem,
    detail: CoursesTodoDetail?,
    courses: List<CourseEntity>
): TaskEntity {
    val course = matchCourse(item.courseName, courses)?.course
    val due = item.dueTimestamp ?: detail?.dueTimestamp

    return TaskEntity(
        id = 0L,
        courseId = course?.id ?: TaskEntity.UNLINKED_COURSE_ID,
        courseName = course?.name ?: TaskEntity.UNLINKED_COURSE_NAME,
        courseCategory = course?.category ?: "",
        courseColorHex = course?.colorHex ?: TaskEntity.UNLINKED_COLOR_HEX,
        title = item.title,
        description = buildNote(detail),
        // 学在浙大上的「待办」就是作业。归到「课后作业」这一类，
        // 用户在清单页按类型筛的时候能一眼找到它。
        taskType = TaskType.POST_CLASS.name,
        dueDateTimestamp = due ?: TaskEntity.NO_DUE_TIMESTAMP,
        dueDateString = due?.let { AppZone.format(DUE_DATE_STRING_PATTERN, it) } ?: "",
        isAutoGenerated = false
    )
}

/**
 * 备注 = 作业说明 + 附件清单。
 *
 * 附件名字也写进去：弹层里看得到附件，但弹层关掉之后只剩这条待办，
 * 而「交了哪几个文件」恰恰是做完这份作业最后要回头确认的东西。
 */
private fun buildNote(detail: CoursesTodoDetail?): String {
    val parts = ArrayList<String>()
    detail?.description?.takeIf { it.isNotBlank() }?.let { parts.add(it) }
    detail?.attachments?.takeIf { it.isNotEmpty() }?.let { list ->
        parts.add("附件：" + list.joinToString("、") { it.name })
    }
    return parts.joinToString("\n\n")
}

/** 与待办库里 `dueDateString` 同一套格式（见 `TaskEntity.dueDateString`）。 */
private const val DUE_DATE_STRING_PATTERN = "yyyy-MM-dd HH:mm"
