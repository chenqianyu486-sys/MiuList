package com.example.data.source.weather

/**
 * 界面上用哪一套空气质量指数。
 *
 * 两套的**六档名称**一样（优 / 良 / 轻度污染 / 中度污染 / 重度污染 / 严重污染），
 * 六档的**指数边界**也都是 50 / 100 / 150 / 200 / 300 —— 但
 * **浓度到指数的换算不一样**：同样的 PM2.5 35 µg/m³，国标是 50（优/良边界），
 * 美国 EPA 是 99（良边缘）；75 µg/m³ 时国标 100，美国约 161。
 *
 * 所以这不是“把同一个数换个说法”，而是两个不同的数。服务端两份都算、
 * 都写进 weather.json，这里只决定界面显示哪一份；**不做任何单位换算**。
 *
 * 默认用 [CN]：这个 App 面向国内用户，他们比较的是国内天气 App / 国控站。
 * [US] 留给想看 Open-Meteo 原生口径的人 —— 它的 `us_aqi` 是 24h 滑动平均的
 * 模式值，和国标不是一回事。
 */
enum class AqiStandard(val label: String) {
    CN("中国国标"),
    US("美国 AQI")
}
