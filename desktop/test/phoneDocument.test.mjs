test('认出手机导出的整机快照', () => {
  assert.equal(isPhoneDocument(phoneExport), true);
});

test('网页端自己的载荷不是手机文档', () => {
  assert.equal(isPhoneDocument({ app: 'MiuList', kind: 'desktop-snapshot', snapshot: {} }), false);
  assert.equal(isPhoneDocument(null), false);
  assert.equal(isPhoneDocument({ tasks: [] }), false);
});

test('课程从 timetable 里取出来 —— 以前丢的就是这一块', () => {
  const parts = decodePhoneDocument(phoneExport);
  assert.ok(parts);
  assert.equal(parts.courses.length, 1);
  assert.equal(parts.courses[0].name, '大学物理');
  assert.equal(parts.courses[0].key, 'PHYS1001|大学物理|王芳');
  assert.equal(parts.courses[0].slots[0].startPeriod, 3);
  assert.deepEqual(parts.courses[0].slots[0].weeks, [1, 2, 3]);
});

test('考试从 exams 里取出来，并认得出它属于哪门课', () => {
  const parts = decodePhoneDocument(phoneExport);
  assert.ok(parts);
  assert.equal(parts.exams.length, 1);
  assert.equal(parts.exams[0].courseName, '大学物理');
  assert.equal(parts.exams[0].seat, '12');
  // 颜色是按课程代码回查出来的 —— 手机那份不带。
  assert.equal(parts.exams[0].colorHex, '#93C5FD');
});

test('待办补上课程名与颜色 —— 手机那份不带这三个字段', () => {
  const parts = decodePhoneDocument(phoneExport);
  assert.ok(parts);
  assert.equal(parts.tasks.length, 1);
  assert.equal(parts.tasks[0].courseName, '大学物理');
  assert.equal(parts.tasks[0].courseCategory, '公共基础');
  assert.equal(parts.tasks[0].courseColorHex, '#93C5FD');
});

test('自定义分类补出落库用的 key', () => {
  const parts = decodePhoneDocument(phoneExport);
  assert.ok(parts);
  assert.equal(parts.taskTypes.length, 1);
  assert.equal(parts.taskTypes[0].name, 'CUSTOM:type-1');
  assert.equal(parts.taskTypes[0].label, '实验报告');
});

test('校历与周课表都带过来', () => {
  const parts = decodePhoneDocument(phoneExport);
  assert.ok(parts);
  assert.equal(parts.calendar.termConfigs[0].Year, '2026-2027');
  assert.equal(parts.calendar.tweaks[0].TweakType, 'Clear');
  assert.equal(parts.calendar.periods[0].startTime, '08:00');
  assert.equal(parts.timetable.totalWeeks, 16);
  assert.equal(parts.timetable.weeks[0].days[0].date, '2026-09-21');
});

test('不是手机文档就返回 null', () => {
  assert.equal(decodePhoneDocument({ app: 'MiuList' }), null);
});

test('紧凑写法的开课周次也认得', () => {
  assert.deepEqual(decodeWeeks([1, 2, 3]), [1, 2, 3]);
  assert.deepEqual(decodeWeeks('1-3'), [1, 2, 3]);
  assert.deepEqual(decodeWeeks('1-16周(单)'), [1, 3, 5, 7, 9, 11, 13, 15]);
  assert.deepEqual(decodeWeeks('1-8,10-12'), [1, 2, 3, 4, 5, 6, 7, 8, 10, 11, 12]);
  // 解析不出来就当每周 —— 宁可多显示几周，也不要整门课消失。
  assert.equal(decodeWeeks('看不懂'), undefined);
  assert.equal(decodeWeeks(null), undefined);
});

