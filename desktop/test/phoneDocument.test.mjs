/**
 * 手机导出 → 网页端导入的解码器。
 *
 * 跑法：`npm test`（Node 自带的 test runner + 类型擦除，不需要额外依赖）。
 *
 * ## 这一层守的是什么
 *
 * 以前网页端**读不懂**手机导出的文件：`unpack()` 看到顶层有 `tasks`
 * 就把整份文档当成了本机快照，而 `normalizeSnapshot` 只认网页端自己的字段 ——
 * 课程在手机那边是嵌在 `timetable.courses` 里的（顶层找不到），
 * 考试手机那边在 v4 之前根本没带，周课表的形状也对不上。
 *
 * 结果是**待办进来了、课表与考试全丢了、周视图空着**，
 * 而界面上还提示「已导入备份」。这一层就是把那条路修通。
 */
