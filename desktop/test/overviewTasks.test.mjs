/**
 * 总览页"全部待办"的筛选、排序与渲染逻辑。
 *
 * 跑法：`npm test`（Node 自带的 test runner + 类型擦除，不需要额外依赖）。
 *
 * ## 这一层守的是什么
 *
 * 总览待办列表从"今天的待办"改为"全部待办"后，必须：
 * - 逾期、今天、未来、无截止日期的未完成任务全部入选
 * - 已完成任务不入选
 * - sortOpenTasks 排序不被破坏
 * - 数据超过 6 条时不被截断
 * - 组件 DOM 层面真实渲染全部未完成任务，未来任务可见，已完成任务不可见，超过 6 条不截断
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { allOpenTasks, sortOpenTasks, isOverdue } from '../src/core/format.ts';

/** 造一条最小任务。 */
function task(overrides) {
  return {
    syncUid: 'uid-' + Math.random().toString(36).slice(2, 8),
    title: '待办',
    description: '',
    taskType: '',
    taskTypeLabel: '',
    priority: '',
    isCompleted: false,
    completedAt: null,
    startTimeTimestamp: 0,
    dueDateTimestamp: 0,
    dueDateString: '',
    startTimeString: '',
    isAutoGenerated: false,
    week: 0,
    dayOfWeek: 0,
    courseKey: '',
    courseName: '',
    courseCategory: '',
    courseColorHex: '',
    createdAt: Date.now(),
    updatedAt: Date.now(),
    ...overrides,
  };
}

const TODAY = '2026-10-28';

// ─── 入选 / 排除（纯函数） ──────────────────────────

test('逾期的未完成任务入选', () => {
  const tasks = [task({ syncUid: 'overdue', dueDateString: '2026-10-25 23:59' })];
  const result = allOpenTasks(tasks, TODAY);
  assert.equal(result.length, 1);
  assert.equal(result[0].syncUid, 'overdue');
});

test('今天到期的未完成任务入选', () => {
  const tasks = [task({ syncUid: 'today', dueDateString: '2026-10-28 18:00' })];
  const result = allOpenTasks(tasks, TODAY);
  assert.equal(result.length, 1);
  assert.equal(result[0].syncUid, 'today');
});

test('未来到期的未完成任务入选', () => {
  const tasks = [task({ syncUid: 'future', dueDateString: '2026-11-15 12:00' })];
  const result = allOpenTasks(tasks, TODAY);
  assert.equal(result.length, 1);
  assert.equal(result[0].syncUid, 'future');
});

test('没有截止日期的未完成任务入选', () => {
  const tasks = [task({ syncUid: 'no-due', dueDateString: '' })];
  const result = allOpenTasks(tasks, TODAY);
  assert.equal(result.length, 1);
  assert.equal(result[0].syncUid, 'no-due');
});

test('已完成任务不入选', () => {
  const tasks = [
    task({ syncUid: 'done', isCompleted: true, completedAt: Date.now(), dueDateString: '2026-10-28 18:00' }),
  ];
  const result = allOpenTasks(tasks, TODAY);
  assert.equal(result.length, 0);
});

test('混合场景：全部类型的未完成任务入选，已完成排除', () => {
  const tasks = [
    task({ syncUid: 'overdue', dueDateString: '2026-10-20' }),
    task({ syncUid: 'today', dueDateString: '2026-10-28 10:00' }),
    task({ syncUid: 'future', dueDateString: '2026-12-01' }),
    task({ syncUid: 'no-due', dueDateString: '' }),
    task({ syncUid: 'done-past', isCompleted: true, completedAt: Date.now(), dueDateString: '2026-10-15' }),
    task({ syncUid: 'done-today', isCompleted: true, completedAt: Date.now(), dueDateString: '2026-10-28' }),
  ];
  const result = allOpenTasks(tasks, TODAY);
  const ids = result.map((t) => t.syncUid);
  assert.ok(ids.includes('overdue'));
  assert.ok(ids.includes('today'));
  assert.ok(ids.includes('future'));
  assert.ok(ids.includes('no-due'));
  assert.ok(!ids.includes('done-past'));
  assert.ok(!ids.includes('done-today'));
  assert.equal(result.length, 4);
});

// ─── 排序 ───────────────────────────────────────────

test('sortOpenTasks 排序：星标优先 → 逾期优先 → 截止日期升序 → 创建时间降序', () => {
  const tasks = [
    task({ syncUid: 'normal-future', dueDateString: '2026-11-01', priority: '', createdAt: 100 }),
    task({ syncUid: 'star-future', dueDateString: '2026-11-05', priority: 'STAR', createdAt: 200 }),
    task({ syncUid: 'overdue', dueDateString: '2026-10-20', priority: '', createdAt: 300 }),
    task({ syncUid: 'no-due', dueDateString: '', priority: '', createdAt: 400 }),
    task({ syncUid: 'today', dueDateString: '2026-10-28', priority: '', createdAt: 500 }),
  ];
  const result = allOpenTasks(tasks, TODAY);
  const ids = result.map((t) => t.syncUid);
  // 星标最前
  assert.equal(ids[0], 'star-future');
  // 逾期在非星标中最前
  assert.equal(ids[1], 'overdue');
  // 然后按截止日期升序
  assert.equal(ids[2], 'today');
  assert.equal(ids[3], 'normal-future');
  // 无截止日期排最后
  assert.equal(ids[4], 'no-due');
});

// ─── 不截断（纯函数） ───────────────────────────────

test('纯函数：超过 6 条数据不截断', () => {
  const tasks = Array.from({ length: 10 }, (_, i) =>
    task({ syncUid: `t-${i}`, dueDateString: `2026-10-${String(20 + i).padStart(2, '0')}`, createdAt: i }),
  );
  const result = allOpenTasks(tasks, TODAY);
  assert.equal(result.length, 10, '应返回全部 10 条未完成任务，不截断');
});

test('纯函数：20 条数据全部返回', () => {
  const tasks = Array.from({ length: 20 }, (_, i) =>
    task({ syncUid: `big-${i}`, createdAt: i }),
  );
  const result = allOpenTasks(tasks, TODAY);
  assert.equal(result.length, 20);
});

// ─── isOverdue 兼容 ─────────────────────────────────

test('isOverdue 对逾期任务返回 true', () => {
  const t = task({ dueDateString: '2026-10-25 23:59' });
  assert.equal(isOverdue(t, TODAY), true);
});

test('isOverdue 对今天/未来/无日期/已完成返回 false', () => {
  assert.equal(isOverdue(task({ dueDateString: '2026-10-28' }), TODAY), false);
  assert.equal(isOverdue(task({ dueDateString: '2026-11-01' }), TODAY), false);
  assert.equal(isOverdue(task({ dueDateString: '' }), TODAY), false);
  assert.equal(isOverdue(task({ isCompleted: true, dueDateString: '2026-10-20' }), TODAY), false);
});

// ─── 组件 / DOM 渲染验收 ────────────────────────────

test('总览组件 DOM 渲染：全部未完成任务展示、未来任务可见、已完成任务不可见、超过 6 条不截断', async () => {
  // 准备包含逾期、今天、未来、无日期、已完成以及超过 6 条的样本数据
  const testTasks = [
    task({ syncUid: 'dom-overdue', title: '逾期测试任务', dueDateString: '2026-10-25 12:00', createdAt: 1 }),
    task({ syncUid: 'dom-today', title: '今天测试任务', dueDateString: '2026-10-28 15:00', createdAt: 2 }),
    task({ syncUid: 'dom-future', title: '未来测试任务', dueDateString: '2026-11-20 09:00', createdAt: 3 }),
    task({ syncUid: 'dom-nodue', title: '无日期测试任务', dueDateString: '', createdAt: 4 }),
    task({ syncUid: 'dom-done', title: '已完成测试任务', isCompleted: true, completedAt: Date.now(), dueDateString: '2026-10-28 12:00', createdAt: 5 }),
    task({ syncUid: 'dom-extra-6', title: '额外任务6', createdAt: 6 }),
    task({ syncUid: 'dom-extra-7', title: '额外任务7', createdAt: 7 }),
    task({ syncUid: 'dom-extra-8', title: '额外任务8', createdAt: 8 }),
    task({ syncUid: 'dom-extra-9', title: '额外任务9', createdAt: 9 }),
    task({ syncUid: 'dom-extra-10', title: '额外任务10', createdAt: 10 }),
  ];

  const mockSnapshot = {
    protocol: 1,
    revision: 1,
    generatedAt: Date.now(),
    today: '2026-10-28',
    weekday: 3,
    deviceName: 'TestDevice',
    appVersion: '1.0',
    latestEditAt: Date.now(),
    utcOffsetMinutes: 480,
    hasCourses: false,
    hasExams: false,
    hasTaskTypes: false,
    tasks: testTasks,
    taskTypes: [],
    courses: [],
    exams: [],
    todayCourses: [],
  };

  globalThis.localStorage = {
    getItem: (key) => (key === 'miulist.snapshot' ? JSON.stringify(mockSnapshot) : null),
    setItem: () => {},
    removeItem: () => {},
  };

  const { createServer } = await import('vite');
  const React = (await import('react')).default;
  const ReactDOMServer = (await import('react-dom/server')).default;

  const server = await createServer();
  try {
    const modOverview = await server.ssrLoadModule('/src/views/Overview.tsx');
    const html = ReactDOMServer.renderToString(React.createElement(modOverview.Overview));

    // 1. 标题与计数：标题为"全部待办"，数量为全部 9 条未完成任务
    assert.ok(html.includes('全部待办'), '标题应为"全部待办"');
    assert.ok(!html.includes('今天的待办'), '旧标题"今天的待办"不应出现');
    assert.ok(html.includes('<span class="count-badge">9</span>'), 'count badge 应显示未完成总数 9');

    // 2. 逾期、今天、未来、无日期未完成任务均实际渲染在 DOM 中
    assert.ok(html.includes('逾期测试任务'), '逾期任务应在 DOM 中');
    assert.ok(html.includes('今天测试任务'), '今天到期任务应在 DOM 中');
    assert.ok(html.includes('未来测试任务'), '未来到期任务应在 DOM 中（打破原 inTodayList 限制）');
    assert.ok(html.includes('无日期测试任务'), '无截止日期任务应在 DOM 中');

    // 3. 超过 6 条未截断：第 7、8、9 条未完成任务全部渲染在 DOM 中
    assert.ok(html.includes('额外任务6'), '额外任务6 应在 DOM 中');
    assert.ok(html.includes('额外任务7'), '额外任务7（超过第6条）应在 DOM 中');
    assert.ok(html.includes('额外任务8'), '额外任务8（超过第6条）应在 DOM 中');
    assert.ok(html.includes('额外任务9'), '额外任务9（超过第6条）应在 DOM 中');
    assert.ok(html.includes('额外任务10'), '额外任务10（超过第6条）应在 DOM 中');

    // 4. 已完成任务绝对不渲染在 DOM 中
    assert.ok(!html.includes('已完成测试任务'), '已完成任务不应出现在总览 DOM 中');

    // 5. 移除原误导性的"还有 N 条待办"
    assert.ok(!html.includes('条待办 <svg'), '不应出现"还有 N 条待办"按钮');
    assert.ok(!html.includes('还有'), '不应出现"还有"提示');
  } finally {
    await server.close();
  }
});

