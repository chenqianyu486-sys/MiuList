import { Check, Sparkles, Star } from 'lucide-react';
import { dueLabel, hexToRgba, isDueToday, isOverdue } from '../core/format';
import { taskTypeOf } from '../core/taskTypes';
import type { Task, TaskTypeOption } from '../core/types';
import { Chip, cx } from './ui';

export function TaskCard({
  task,
  today,
  types,
  compact = false,
  onOpen,
}: {
  task: Task;
  today: string;
  types: TaskTypeOption[];
  compact?: boolean;
  onOpen: (task: Task) => void;
}) {
  const type = taskTypeOf(task, types);
  const due = dueLabel(task, today);
  const overdue = isOverdue(task, today);
  const todayDue = isDueToday(task, today);
  const color = task.courseColorHex || '#C9D0D8';

  return (
    <div
      className={cx(
        'task-card',
        compact && 'is-compact',
        task.isCompleted && 'is-done',
        overdue && 'is-overdue',
        !overdue && todayDue && 'is-today',
      )}
      style={{ '--course': color, '--course-tint': hexToRgba(color, 0.12) } as never}
      role="button"
      tabIndex={0}
      onClick={() => onOpen(task)}
      onKeyDown={(event) => {
        if (event.key === 'Enter' || event.key === ' ') {
          event.preventDefault();
          onOpen(task);
        }
      }}
      aria-label={`${task.title || '无标题待办'}${task.isCompleted ? '，已完成' : ''}`}
    >
      <button
        type="button"
        className={cx('task-check', task.isCompleted && 'is-checked')}
        aria-label={task.isCompleted ? '标记为未完成' : '标记为已完成'}
        aria-pressed={task.isCompleted}
        onClick={(event) => {
          event.stopPropagation();
          void import('../core/sync').then((mod) => mod.toggleTask(task));
        }}
      >
        {task.isCompleted ? <Check size={14} strokeWidth={3} /> : null}
      </button>

      <div className="task-body">
        <div className="task-title-row">
          <span className="task-dot" style={{ background: color }} aria-hidden="true" />
          <span className="task-title">{task.title || '(无标题待办)'}</span>
          {task.isAutoGenerated ? (
            <span className="task-auto" title="由课程联动自动生成">
              <Sparkles size={12} />
            </span>
          ) : null}
        </div>
        <div className="task-meta">
          {due ? <span className={cx('task-due', overdue && 'is-overdue')}>{due}</span> : null}
          {task.courseName ? <span className="task-course">{task.courseName}</span> : null}
        </div>
        {(overdue || todayDue || type.label) && (
          <div className="task-chips">
            {overdue ? <Chip className="chip--danger">逾期</Chip> : null}
            {!overdue && todayDue ? <Chip className="chip--lime">今天截止</Chip> : null}
            {type.label ? (
              <Chip color={type.colorHex} ink={type.inkHex}>
                {type.label}
              </Chip>
            ) : null}
          </div>
        )}
      </div>

      <button
        type="button"
        className={cx('task-star', task.priority === 'STAR' && 'is-on')}
        aria-label={task.priority === 'STAR' ? '取消星标' : '加星标'}
        aria-pressed={task.priority === 'STAR'}
        title={task.priority === 'STAR' ? '取消星标' : '加星标'}
        onClick={(event) => {
          event.stopPropagation();
          void import('../core/sync').then((mod) => mod.toggleStar(task));
        }}
      >
        <Star
          size={18}
          fill={task.priority === 'STAR' ? 'currentColor' : 'none'}
          strokeWidth={2}
        />
      </button>
    </div>
  );
}
