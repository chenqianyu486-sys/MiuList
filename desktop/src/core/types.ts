/**
 * 一个待办分类。
 *
 * `name` 是**落库用的 key**，不是显示名：内置类型存枚举名（`PRE_STUDY`），
 * 自定义类型存 `CUSTOM:<id>` —— 与手机端 `tasks.taskType` 一列的约定一致。
 * 手机发过来的自定义分类只有 `id` 与 `label`，key 由前端按 `CUSTOM:<id>` 补出来
 * （见 `taskTypes.ts`）；补不出来时 `name` 为空串，这条分类就只是「看得见、选不了」。
 */
export type TaskTypeOption = {
  name: string;
  label: string;
  colorHex: string;
  inkHex: string;
  isCustom?: boolean;
  /** 自定义分类的稳定 id（手机端的主键）。 */
  id?: string;
  sortOrder?: number;
};

/**
 * **原始校历**：学期起止、调休规则、作息表。
 *
 * 与渲染好的 `Timetable`（周课表格栅格）是两回事：
 * - `Timetable` 是**结果**（哪一天上什么课），手机算好发过来，网页端只画；
 * - `CalendarData` 是**规则**（这一学期从哪天到哪天、哪天停课、几点上课）。
 *
 * 网页端显示周课表用不到它，但**导出的备份要靠它**：
 * 有了它，这份 JSON 才是一份完整的「整机快照」，
 * 而不是「一堆待办 + 一张画好的表」。
 *
 * 字段名与手机端 JSON **逐字相同**（`Year` / `Begin` / `TweakType` …），
 * 这样两端导出的文件可以直接互相读，不用再做一层改名。
 */
export type CalendarData = {
  /** 一期学期的起止。`Begin` / `End` 是 `YYYYMMDD` 的整数。 */
  termConfigs: {
    Year?: string;
    Term?: number;
    Begin?: number;
    End?: number;
    FirstWeekNo?: number;
  }[];
  /** 上课学期（`"2026-2027:0"` 这种写法）。 */
  classTerms: string[];
  /** 调休规则：停课 / 搬课 / 互换。`From` / `To` 都是 `YYYYMMDD` 整数。 */
  tweaks: {
    TweakType?: string;
    Description?: string;
    From?: number;
    To?: number;
  }[];
  /** 作息表：第几节几点到几点。 */
  periods: {
    period?: number;
    startTime?: string;
    endTime?: string;
    section?: string;
  }[];
};

